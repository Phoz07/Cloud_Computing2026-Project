#!/usr/bin/env bash
# Copy the third-party credentials from the root .env into the gitignored
# infra/terraform/*.auto.tfvars that Terraform turns into Secrets Manager secrets
# (google.auto.tfvars, gmail.auto.tfvars, stripe.auto.tfvars). Prints key NAMES
# and set/empty only — never a value. A group whose required keys are empty is
# not written (and a stale file for it is removed), so that feature stays off.
#
#   bash scripts/sync-secrets.sh        (make secrets also applies just those secrets)
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
python3 -I - "$ROOT" <<'PY'
import json, os, sys
root = sys.argv[1]
env = {}
for line in open(os.path.join(root, ".env"), encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("#") or "=" not in line:
        continue
    k, v = line.split("=", 1)
    v = v.strip()
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        v = v[1:-1]
    env[k.strip()] = v

# .env KEY -> terraform variable; a group is on only when ALL its `need` keys are set.
groups = {
    "google": {"need": ["GOOGLE_CLIENT_ID", "GOOGLE_CLIENT_SECRET"],
               "map": {"GOOGLE_CLIENT_ID": "google_client_id", "GOOGLE_CLIENT_SECRET": "google_client_secret"}},
    "gmail":  {"need": ["GMAIL_USER", "GMAIL_APP_PASSWORD"],
               "map": {"GMAIL_USER": "gmail_user", "GMAIL_APP_PASSWORD": "gmail_app_password", "MAIL_FROM": "mail_from"}},
    "stripe": {"need": ["STRIPE_SECRET_KEY"],
               "map": {"STRIPE_SECRET_KEY": "stripe_secret_key", "STRIPE_WEBHOOK_SECRET": "stripe_webhook_secret"}},
}
hcl = lambda s: json.dumps(s).replace("${", "$${").replace("%{", "%%{")  # HCL: no interpolation
for name, g in groups.items():
    path = os.path.join(root, "infra", "terraform", f"{name}.auto.tfvars")
    on = all(env.get(k) for k in g["need"])
    if on:
        with open(path, "w", encoding="utf-8") as f:
            f.write(f"# Generated by scripts/sync-secrets.sh from .env — gitignored, do not edit.\n")
            for k, var in g["map"].items():
                f.write(f"{var} = {hcl(env.get(k, ''))}\n")
        os.chmod(path, 0o600)
    elif os.path.exists(path):
        os.remove(path)
    status = ", ".join(f"{k}={'set' if env.get(k) else 'EMPTY'}" for k in g["map"])
    print(f"{name:7s} {'ON ' if on else 'off'}  {status}")
PY
